export type IconName = keyof typeof REGISTRY;

/**
 * Reusable icon. Renders a Lucide icon by semantic name via NgComponentOutlet,
 * so the whole app shares one icon vocabulary and consistent sizing.
 *
 * Usage: `<app-icon name="file-text" [size]="18" class="text-muted" />`
 */
@Component({
  selector: 'app-icon',
  imports: [NgComponentOutlet],
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `<ng-container
    [ngComponentOutlet]="cmp()"
    [ngComponentOutletInputs]="inputs()"
  />`,
  host: {
    class: 'inline-flex shrink-0 items-center justify-center',
    '[style.width.px]': 'size()',
    '[style.height.px]': 'size()',
  },
})
export class IconComponent {
  readonly name = input.required<IconName>();
  readonly size = input(18);
  readonly strokeWidth = input(2);
  /** Extra classes forwarded onto the rendered <svg>. */
  readonly class = input('');

  protected readonly cmp = computed<Type<unknown>>(() => REGISTRY[this.name()]);
  protected readonly inputs = computed(() => ({
    size: this.size(),
    strokeWidth: this.strokeWidth(),
    class: this.class(),
  }));
}
